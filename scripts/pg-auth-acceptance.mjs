import { randomBytes,randomUUID } from 'node:crypto';
import { mkdtemp,writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join,isAbsolute } from 'node:path';
import sharp from 'sharp';
import pg from 'pg';
import { createPool } from '../server/postgres/config.mjs';
import { migrate } from '../server/postgres/migrations.mjs';
import { importSnapshot } from '../server/postgres/importer.mjs';
import { enableMirror } from '../server/postgres/mirror.mjs';
import { createCoverStorage } from '../server/cover-storage.mjs';
import { hashPassword } from '../server/auth.mjs';
import { authGrants } from '../server/security/grants.mjs';
import { record } from '../tests/fixtures/collection.mjs';
import { wish } from '../tests/fixtures/wishlist.mjs';
if(process.env.NODE_ENV!=='development')throw Error('Explicit development environment required');
const url=new URL(process.env.PG_LOCAL_ADMIN_URL);
if(url.hostname!=='127.0.0.1'||url.port!=='55464'||decodeURIComponent(url.username)!=='vinyl_4a_admin'||url.pathname!=='/postgres'||url.search||url.hash)throw Error('Existing dedicated user-local admin runtime required');
const suffix=randomBytes(6).toString('hex'),database='vinyl_4a_acceptance_4c_'+suffix,role='vinyl_4c_'+suffix,backup='vinyl_4c_backup_'+suffix;
const parent=process.env.PG_AUTH_ACCEPTANCE_PARENT || tmpdir();
if(!isAbsolute(parent))throw Error('Absolute acceptance parent required');
const password=randomBytes(32).toString('hex'),root=await mkdtemp(join(parent,'vinyl-4c-acceptance-'));
const admin=new pg.Pool({connectionString:url.href,max:1,connectionTimeoutMillis:3000});let pool;
try{
 await admin.query(`CREATE ROLE "${role}" LOGIN PASSWORD '${password}' NOSUPERUSER NOCREATEDB NOCREATEROLE`);
 await admin.query(`CREATE ROLE "${backup}" NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE`);
 await admin.query(`CREATE DATABASE "${database}"`);
 const marker=randomBytes(24).toString('hex');
 await admin.query(`COMMENT ON DATABASE "${database}" IS 'vinyl-4c-acceptance:${marker}'`);
 url.pathname='/'+database;pool=createPool(url.href);await migrate(pool);
 const ownerId='5c621d27-1477-46d3-a1f9-92311f53856d',covers=createCoverStorage(join(root,'covers'));
 const png=await sharp({create:{width:480,height:480,channels:3,background:'#8d6048'}}).png().toBuffer();
 await writeFile(join(root,'sample.png'),png,{mode:0o600});const cover=await covers.prepare(png);
 await importSnapshot(pool,{importKey:'local_stage4c_fixture',user:{id:ownerId,login:'obrattsev',email:'fixture-owner@example.test',collectionPublic:true,wishlistPublic:true},collection:[{...record,id:randomUUID(),artist:'Fixture Owner',album:'Owner Collection',coverId:cover,favorite:true}],wishlist:[{...wish,id:randomUUID(),artist:'Fixture Owner',album:'Owner Wishlist',coverId:cover}],covers:[cover]},{dryRun:false});
 await enableMirror(pool,ownerId);
 await pool.query(`GRANT CONNECT ON DATABASE "${database}" TO "${role}","${backup}"; GRANT USAGE ON SCHEMA vinyl TO "${role}","${backup}";
 GRANT SELECT ON ALL TABLES IN SCHEMA vinyl TO "${role}","${backup}";
 GRANT INSERT,UPDATE,DELETE ON vinyl.collection_records,vinyl.wishlist_records TO "${role}";
 GRANT INSERT ON vinyl.covers TO "${role}";
 GRANT UPDATE(updated_at) ON vinyl.users TO "${role}";
 GRANT UPDATE(business_writes) ON vinyl.runtime_control TO "${role}";
 GRANT UPDATE(generation,next_attempt_at,dirty_since) ON vinyl.mirror_state TO "${role}";
 GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA vinyl TO "${role}";
 ${authGrants(role,backup)}`);
 const legacyPassword='local-owner-4C-password',hash=await hashPassword(legacyPassword);
 url.username=role;url.password=password;
 const env={NODE_ENV:'development',DATA_BACKEND:'postgres',DATABASE_URL:url.href,PG_OWNER_ID:ownerId,AUTH_MODE:'multiuser',AUTH_SECRET:randomBytes(32).toString('hex'),AUTH_REGISTRATION_ENABLED:'true',AUTH_LEGACY_ENABLED:'true',OWNER_PASSWORD_HASH:hash,EMAIL_ADAPTER:'capture',EMAIL_CAPTURE_FILE:join(root,'mail','capture.jsonl'),COVERS_DIR:join(root,'covers'),PORT:'8046',APP_ORIGIN:'http://127.0.0.1:8046',MIRROR_ENABLED:'true',MIRROR_OWNER_ID:ownerId,MIRROR_FAKE_FILE:join(root,'mirror.json')};
 await writeFile(join(root,'mirror.json'),JSON.stringify({collection:[],wishlist:[],outage:false}),{mode:0o600});
 await writeFile(join(root,'restart.env'),Object.entries(env).map(([k,v])=>`${k}=${v}`).join('\n')+'\n',{mode:0o600});
 await writeFile(join(root,'stand.json'),JSON.stringify({format:1,database,role,backup,marker,ownerId,legacyPassword,createdAt:new Date().toISOString()},null,2),{mode:0o600});
 console.log(JSON.stringify({root,url:env.APP_ORIGIN+'/auth',fixtureOwnerEmail:'fixture-owner@example.test',legacyPassword,environmentFile:join(root,'restart.env')}));
}finally{await pool?.end();await admin.end();}
